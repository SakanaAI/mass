#!/usr/bin/env python3
"""Review MLR-Bench papers using the official Overall rubric and two external judges.
Missing or shorter-than-200-byte papers receive zero."""
from pathlib import Path
import os
import sys
BENCH_ROOT = Path(os.environ.get("MASS_BENCH_ROOT", str(Path(__file__).resolve().parents[1] / "work"))).resolve()

import argparse, glob, json, os, re, sys, time
_REPO = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "vendor", "mlrbench")
_src = open(os.path.join(_REPO, "mlrbench", "evals", "overall_review.py"), encoding="utf-8").read()
OVERALL_RUBRIC = re.search(r'OVERALL_RUBRIC = """(.*?)"""', _src, re.S).group(1)   # verbatim from the official reviewer


def read_text(p):
    return open(p, encoding="utf-8", errors="replace").read()


def read_combine_files(d, exts=(".py", ".md", ".txt", ".json", ".yaml", ".yml", ".sh", ".csv")):
    out = []
    for root, _, files in os.walk(d):
        for f in sorted(files):
            if f.endswith(exts):
                fp = os.path.join(root, f)
                try: out.append(f"### {os.path.relpath(fp, d)}\n{read_text(fp)[:20000]}")
                except OSError: pass
    return "\n\n".join(out)


def extract_json_between_markers(text):
    m = re.findall(r"```json\s*(.*?)```", text, re.S) or re.findall(r"(\{.*\})", text, re.S)
    for cand in m:
        try: return json.loads(cand)
        except json.JSONDecodeError: continue
    return None

TAIL = """
Please provide a detailed review of the paper, including your scores for each aspect and an overall assessment. Be sure to justify your scores with specific examples from the paper.
Please do not include any personal opinions or biases in your review. Your review should be objective and based solely on the content of the paper. Please provide a confidence score from 1 to 5 for the overall assessment.
Do not hesitate to assign lower scores if the paper does not fully meet the criteria. Avoid giving high scores by default.
IMPORTANT: output the complete JSON object described in the rubric (keys Clarity, Novelty, Soundness, Significance, Overall, Confidence), inside a ```json code block.
"""


def build_prompt(task_md, paper_md, code_text):
    return (OVERALL_RUBRIC + f"\n## Task Description\n```\n{task_md}\n```\n## Paper to Be Reviewed\nNote: The paper is generated by AI and may contain some errors. Please check the paper carefully and provide your review.\n```json\n{paper_md}\n```\n## Code of the Paper\n```json\n{code_text}\n```\n" + TAIL)


def call_openai(model, prompt):
    from openai import OpenAI
    c = OpenAI()
    kw = {"model": model, "messages": [{"role": "user", "content": prompt}], "max_completion_tokens": 16000}
    if not (model.startswith("o1") or model.startswith("o3") or model.startswith("o4") or model.startswith("gpt-5")):
        kw["temperature"] = 0
    r = c.chat.completions.create(**kw)
    return r.choices[0].message.content, {"in": r.usage.prompt_tokens, "out": r.usage.completion_tokens}


def call_anthropic(model, prompt):
    import anthropic
    c = anthropic.Anthropic()
    r = c.messages.create(model=model, max_tokens=16000, messages=[{"role": "user", "content": prompt}])   # temperature not accepted by this model
    return "".join(b.text for b in r.content if getattr(b, "type", "") == "text"), {"in": r.usage.input_tokens, "out": r.usage.output_tokens}


def review_one(trial_dir, judge, task_md, code_limit=60000):
    vd = os.path.join(trial_dir, "verifier"); out = os.path.join(vd, f"review_{judge}.json")
    os.makedirs(vd, exist_ok=True)
    if os.path.exists(out):
        return json.load(open(out))
    paper = os.path.join(vd, "results", "paper.md")
    if not os.path.exists(paper) or os.path.getsize(paper) < 200:
        rec = {"missing_paper": True, "Clarity": {"score": 0}, "Novelty": {"score": 0}, "Soundness": {"score": 0}, "Significance": {"score": 0}, "Overall": {"score": 0}, "Confidence": 5}
        json.dump(rec, open(out, "w"), indent=1); return rec
    paper_md = read_text(paper)[:120000]
    code_dir = os.path.join(vd, "code")
    code_text = (read_combine_files(code_dir) if os.path.isdir(code_dir) else "")[:code_limit]
    prompt = build_prompt(task_md, paper_md, code_text)
    for attempt in range(3):
        try:
            text, usage = (call_anthropic if judge.startswith("claude") else call_openai)(judge, prompt)
            rev = extract_json_between_markers(text)
            if not isinstance(rev, dict): raise ValueError("no json")
            for k in ("Clarity", "Novelty", "Soundness", "Significance", "Overall", "Confidence"):
                if k not in rev: raise ValueError(f"missing {k}")
            rev["_usage"] = usage; rev["_judge"] = judge; rev["missing_paper"] = False
            json.dump(rev, open(out, "w"), indent=1); return rev
        except Exception as e:  # noqa: BLE001
            print(f"  {judge} attempt {attempt+1} failed: {repr(e)[:160]}", flush=True); time.sleep(5)
    return None


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("jobs", nargs="+"); ap.add_argument("--judges", nargs="+", default=["gpt-5.5", "claude-opus-4-8"])
    ap.add_argument("--out", default=None); a = ap.parse_args()
    results = {}
    for j in a.jobs:
        for c in sorted(glob.glob(os.path.join(j, "*", "config.json"))):
            td = os.path.dirname(c); cfg = json.load(open(c)); tp = (cfg.get("task") or {}).get("path") or ""
            task = tp.rstrip("/").split("/")[-1]; task_md = read_text(os.path.join(tp, "task.md")) if tp and os.path.exists(os.path.join(tp, "task.md")) else ""
            rec = {"job": os.path.basename(j.rstrip("/")), "trial": os.path.basename(td), "task": task, "reviews": {}}
            for judge in a.judges:
                rev = review_one(td, judge, task_md)
                if rev: rec["reviews"][judge] = {k: (rev[k]["score"] if isinstance(rev[k], dict) else rev[k]) for k in ("Clarity", "Novelty", "Soundness", "Significance", "Overall", "Confidence")} | {"missing_paper": rev.get("missing_paper", False)}
            sc = [v["Overall"] for v in rec["reviews"].values()]
            rec["overall_mean"] = round(sum(sc) / len(sc), 2) if sc else None
            results[f"{rec['job']}/{task}"] = rec
            print(f"{rec['job']} {task}: " + " | ".join(f"{jn}: overall {v['Overall']} (C{v['Clarity']} N{v['Novelty']} S{v['Soundness']} Sig{v['Significance']}){' [no paper]' if v['missing_paper'] else ''}" for jn, v in rec["reviews"].items()), flush=True)
    if a.out: json.dump(results, open(a.out, "w"), indent=1)


if __name__ == "__main__":
    main()
